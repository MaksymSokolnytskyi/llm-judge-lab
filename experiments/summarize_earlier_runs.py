"""Summarise the three runs that preceded the cross-judge experiment.

Question: before testing the judges, did the generation side work at all?

All three used llama3.1:8b as the generator and qwen2.5:7b as the single judge.

* ``single_turn_ab.jsonl`` -- 20 requests, each answered two ways: A writes a reply from
  scratch, B restyles the dataset's reference reply. A refiner retries up to twice
  while the score is below 8 (the pass mark for this run).
* ``persona_matrix_baseline.jsonl`` -- 10 requests x 5 personas with hand-written
  system prompts, pass mark 7.
* ``persona_matrix_meta_prompted.jsonl`` -- the same 50 cells, but the system prompts
  were rewritten by qwen2.5:7b after it was shown the baseline's failures.

    python experiments/summarize_earlier_runs.py results/earlier_runs
"""

from __future__ import annotations

import argparse
import statistics
from collections import Counter, defaultdict
from collections.abc import Iterable
from pathlib import Path

from judgelab.cross_judge.analysis import read_jsonl


def _distribution(scores: Iterable[int]) -> str:
    counts = Counter(scores)
    return ", ".join(
        f"{score}: {counts[score]}" for score in sorted(counts, reverse=True)
    )


def main() -> None:
    parser = argparse.ArgumentParser(description=(__doc__ or "").splitlines()[0])
    parser.add_argument("folder", type=Path)
    args = parser.parse_args()

    ab = read_jsonl(args.folder / "single_turn_ab.jsonl")
    lines = [
        "# Earlier runs",
        "",
        "Generated by `experiments/summarize_earlier_runs.py`. Generator llama3.1:8b, "
        "judge qwen2.5:7b throughout.",
        "",
        "## Write from scratch (A) vs restyle the reference answer (B)",
        "",
        "| approach | accepted (score >= 8) | mean final score | mean attempts "
        "| score distribution |",
        "|---|---|---|---|---|",
    ]
    for approach in ("A", "B"):
        rows = [r for r in ab if r["approach"] == approach]
        assert len(rows) == 20
        # The prose below claims this; fail loudly if the data ever disagrees.
        assert all(r["score"] == 8 for r in rows if r["accepted"])
        lines.append(
            f"| {approach} | {sum(r['accepted'] for r in rows)}/{len(rows)} "
            f"| {statistics.fmean(r['score'] for r in rows):.2f} "
            f"| {statistics.fmean(r['attempts'] for r in rows):.2f} "
            f"| {_distribution(r['score'] for r in rows)} |"
        )
    lines += [
        "",
        "Every accepted text in both arms scored exactly the pass mark, 8: with a "
        "refine-until-pass loop the judge behaves as a binary gate, so the means say "
        "little about quality beyond the acceptance count.",
    ]

    base = read_jsonl(args.folder / "persona_matrix_baseline.jsonl")
    meta = read_jsonl(args.folder / "persona_matrix_meta_prompted.jsonl")
    assert {r["instruction"] for r in base} == {r["instruction"] for r in meta}
    lines += [
        "",
        "## Hand-written vs meta-prompted system prompts (same 50 cells, pass mark 7)",
        "",
        "| persona | hand-written: accepted | mean | meta-prompted: accepted | mean |",
        "|---|---|---|---|---|",
    ]
    for persona in ("normal", "cheerful", "bad_mood", "passive_aggressive", "toxic"):
        cells = []
        for run in (base, meta):
            rows = [r for r in run if r["persona"] == persona]
            assert len(rows) == 10
            accepted = sum(r["judge_score"] >= 7 for r in rows)
            mean = statistics.fmean(r["judge_score"] for r in rows)
            cells.append(f"{accepted}/10 | {mean:.1f}")
        lines.append(f"| {persona} | {cells[0]} | {cells[1]} |")
    totals: dict[str, int] = defaultdict(int)
    for name, run in (("hand-written", base), ("meta-prompted", meta)):
        totals[name] = sum(r["judge_score"] >= 7 for r in run)
    lines += [
        "",
        f"Total accepted: hand-written {totals['hand-written']}/50, "
        f"meta-prompted {totals['meta-prompted']}/50.",
    ]
    report = "\n".join(lines)
    (args.folder / "REPORT.md").write_text(report + "\n", encoding="utf-8")
    print(report)


if __name__ == "__main__":
    main()
